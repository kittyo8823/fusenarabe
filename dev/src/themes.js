export const THEMES = T.map(([genre, title, lo, hi]) => ({ genre, title, lo, hi }));
export const GENRES = ['すべて', ...new Set(THEMES.map((t) => t.genre))];

export function pickTheme(genre = 'すべて', exclude = null, rnd = Math.random) {
  const list = THEMES.filter((t) => (genre === 'すべて' || t.genre === genre) && t.title !== exclude);
  return list[Math.floor(rnd() * list.length)] || THEMES[0];
}
