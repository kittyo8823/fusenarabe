import assert from 'node:assert/strict';
import * as G from '../src/game.js';
const r = G.newRoom('ABCDEF', { id: 'h', name: 'ホスト' });
G.addPlayer(r, 'a', 'A'); G.addPlayer(r, 'b', 'B');
r.settings.cards = 2;
G.deal(r);
const all = Object.values(r.hands).flat();
assert.equal(all.length, 6);
assert.equal(new Set(all.map((c) => c.n)).size, 6);
const owner = (c) => Object.keys(r.hands).find((k) => r.hands[k].includes(c));
assert.equal(G.place(r, 'a', 'nope', 0.5, 0.5).err, 'card');
// 適当な位置に置く（x は逆順）
all.forEach((c, i) => assert.ok(G.place(r, owner(c), c.cid, 1 - i / 5, 0.3, 'ひんと' + i).ok));
assert.equal(G.place(r, owner(all[0]), all[0].cid, 0.1, 0.1).err, 'placed');
assert.ok(G.allPlaced(r));
assert.equal(r.phase, 'play', 'no auto reveal');
let ps = G.publicState(r);
assert.ok(ps.board.every((b) => b.n == null), 'no numbers before reveal');
assert.ok(G.startReveal(r));
ps = G.publicState(r);
assert.equal(ps.board.find((b) => b.turn === 1).cid, all[5].cid, 'leftmost first');
assert.ok(G.flipNext(r));
ps = G.publicState(r);
assert.equal(ps.board.filter((b) => b.n != null).length, 1);
assert.equal(ps.board.find((b) => b.n != null).n, all[5].n);
while (G.flipNext(r));
ps = G.publicState(r);
assert.equal(ps.revealed, 6); assert.equal(ps.toReveal, 6);
assert.ok(!G.flipNext(r));
// 途中でめくり始め
G.backToLobby(r); G.deal(r);
const a2 = Object.values(r.hands).flat();
G.place(r, owner(a2[0]), a2[0].cid, 0.2, 0.2);
G.startReveal(r);
assert.equal(G.publicState(r).toReveal, 1);
assert.equal(G.place(r, owner(a2[1]), a2[1].cid, 0.2, 0.2).err, 'phase');
// clamp
G.backToLobby(r); G.deal(r);
const a3 = Object.values(r.hands).flat()[0];
G.place(r, owner(a3), a3.cid, 7, -3);
assert.deepEqual([r.board[0].x, r.board[0].y], [1, 0]);
const f = G.newRoom('X', { id: 'h', name: 'h' });
for (let i = 0; i < 9; i++) assert.ok(G.addPlayer(f, 'p' + i, 'p').ok);
assert.equal(G.addPlayer(f, 'z', 'z').err, 'full');
console.log('game tests ok');
